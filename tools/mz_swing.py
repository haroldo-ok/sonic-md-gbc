#!/usr/bin/env python3
"""
Marble Zone swinging platform art (`15 Swinging Platforms.asm`, `Map_Swing_GHZ` + `ArtTile_GHZ_MZ_Swing`).

GHZ and MZ share the swinging platform's art and mappings; only the palette differs. In MZ the plank and anchor use
`Tile_Pal3` (Marble Zone palette line 2: lavender / blue-violet) and the chain links are forced to line 1 (grey).
The MZ zone-prop slots (tiles 40..67) are full, but MZ has no Yadrin or Splats, so their sprite slot `ZSPR_ENEMY5`
(tiles 32..39 of the MZ sprite bank) is free. This tool renders the three frames, halves them, quantises every cell to
fixed OBJ palettes (cobalt for the plank / anchor, steel for the chain: the zone's own two palettes are green / grey),
de-duplicates cells under flips and writes:

    generated/zp_mz_swing.h      PropCell tables `zp_mz_swing` (plank), `zp_mz_chain`, `zp_mz_anchor`
    generated/bank_051.c         `vset_2_sprtiles` tiles 32..39 patched

Usage: python3 tools/mz_swing.py
"""
from __future__ import annotations

import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ghz_props as G  # noqa: E402
import zart  # noqa: E402
from gfx_converter import encode_2bpp_tile, load_md_palette_bytes, rgb555_to_rgb8  # noqa: E402
from md_symbols import S1DisasmROM  # noqa: E402

GEN_DIR = G.GEN_DIR
VSET = 2
FIRST, SLOTS = 32, 8                      # ZSPR_ENEMY5 (unused in MZ)

# fixed OBJ palettes from `g_default_obj_pals` (src/main.c): colours 1..3
FIXED = {
    0: [(8, 8, 24), (36, 76, 248), (252, 240, 212)],
    1: [(16, 16, 24), (244, 28, 24), (252, 252, 252)],
    2: [(108, 52, 0), (252, 204, 0), (252, 252, 252)],
    3: [(16, 16, 28), (244, 36, 24), (252, 248, 232)],
    4: [(16, 24, 56), (36, 148, 248), (248, 252, 252)],
    5: [(24, 28, 36), (148, 168, 192), (252, 252, 252)],
}


def render():
    s1 = S1DisasmROM(zart.S1)
    img = zart.vram_image(["PLC_MZ", "PLC_MZ2"])
    base = zart.const("ArtTile_GHZ_MZ_Swing")
    td = {k - base: v for k, v in img.items()}
    lines = zart.pal_lines("Marble Zone.bin")           # [0] = CRAM line 1, [1] = CRAM line 2 (Tile_Pal3)
    frames = s1.parse_sprite_mapping_table(s1.sym("Map_Swing_GHZ"), 3)
    out = {}
    # The plank is blue-violet (lavender stripes, green bolts). Steel (5) has the least colour error but reads as a flat
    # grey bar; cobalt (4) keeps the light / dark stripes and the blue cast, so the plank and anchor use it.
    for name, fr, line, pals in (("swing", frames[0], lines[1], (4,)),
                                 ("chain", frames[1], lines[0], (5,)),      # `bclr #6`: chain links on line 1 (grey)
                                 ("anchor", frames[2], lines[1], (4,))):
        rgba, x0, y0 = G._render(fr, td, line)
        cells = G._cut_cells(G._half(rgba), x0 // 2, y0 // 2)
        cells.sort(key=lambda c: (c[1], c[0]))
        out[name] = (cells, pals)
    return out


def build():
    groups = render()
    # one palette for the whole plank (and anchor): the fixed palette with the least total error
    def best_pal(cells, allowed):
        return min(allowed, key=lambda p: sum(G._err(t, FIXED[p]) for _, _, t in cells))
    uniq, index, tables, chosen = [], {}, {}, {}
    for name, (cells, pals) in groups.items():
        pal = best_pal(cells, pals or tuple(FIXED))
        chosen[name] = pal
        rows = []
        for dx, dy, t in cells:
            q = G._quant(t, FIXED[pal])
            hit = None
            for v, fh, fv in G._flips(q):
                k = (pal, np.ascontiguousarray(v).tobytes())
                if k in index:
                    tid, th, tv = index[k]
                    hit = (tid, fh ^ th, fv ^ tv)
                    break
            if hit is None:
                tid = len(uniq)
                uniq.append(q)
                for v, fh, fv in G._flips(q):
                    index.setdefault((pal, np.ascontiguousarray(v).tobytes()), (tid, fh, fv))
                hit = (tid, 0, 0)
            rows.append((dx, dy, FIRST + hit[0], 0x08 | pal | (0x20 if hit[1] else 0) | (0x40 if hit[2] else 0)))
        tables[name] = rows
    assert len(uniq) <= SLOTS, len(uniq)
    tiles = b"".join(encode_2bpp_tile(q) for q in uniq)
    return tables, tiles, chosen


def write(tables, tiles, chosen):
    L = ["/* GENERATED by tools/mz_swing.py - Marble Zone swinging platform (0x15) cells in ZSPR_ENEMY5 (tiles 32..39) */",
         "#ifndef ZP_MZ_SWING_H", "#define ZP_MZ_SWING_H", ""]
    for name, rows in tables.items():
        L.append(f"/* {name}: OBJ palette {chosen[name]} */")
        L.append(f"#define ZP_MZ_{name.upper()}_N {len(rows)}")
        L.append(f"static const PropCell zp_mz_{name}[{len(rows)}] = {{")
        L += [f"    {{ {dx}, {dy}, {t}, 0x{a:02X} }}," for dx, dy, t, a in rows]
        L += ["};", ""]
    L += ["#endif", ""]
    open(os.path.join(GEN_DIR, "zp_mz_swing.h"), "w").write("\n".join(L))
    path = os.path.join(GEN_DIR, f"bank_{47 + 2 * VSET:03d}.c")
    src = open(path).read()
    m = re.search(r"(const uint8_t vset_%d_sprtiles\[2048\] = \{)(.*?)(\n\};)" % VSET, src, re.S)
    vals = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(2))]
    assert len(vals) == 2048
    vals[FIRST * 16:FIRST * 16 + len(tiles)] = list(tiles)
    lines = ["    " + ", ".join(f"0x{v:02X}" for v in vals[i:i + 24]) + "," for i in range(0, 2048, 24)]
    open(path, "w").write(src[:m.start(2)] + "\n" + "\n".join(lines) + src[m.end(2):])
    print(f"wrote generated/zp_mz_swing.h ({len(tiles) // 16} tiles, palettes {chosen}) and patched vset_{VSET}_sprtiles")


if __name__ == "__main__":
    write(*build())
